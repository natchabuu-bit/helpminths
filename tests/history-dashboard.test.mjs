// Actual provided annual reports and audited 2569 counts, never synthetic clinical results.
const baseURL = process.env.HELPMINTHS_TEST_URL || 'http://127.0.0.1:8084'
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined)
let browser
before(async () => {
  assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(new URL(baseURL).hostname))
  const response = await fetch(`${baseURL}/api/platform/operations/status`)
  assert.equal(response.status, 200)
  assert.equal(response.headers.has('x-helpminths-test-fixture'), false)
  const metadata = await response.json()
  assert.deepEqual(metadata.capabilities.available_years, [2568, 2569])
  browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
})
after(async () => browser?.close())
async function open() {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block', timezoneId: 'Asia/Bangkok' }), page = await context.newPage()
  const errors = [], writes = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!['GET', 'HEAD', 'OPTIONS'].includes(request.method())) writes.push(request.method() + ' ' + request.url()); if (new URL(request.url()).pathname === '/api/platform/operations/dashboard') requests.push(new URL(request.url())) })
  await page.goto(`${baseURL}/#dashboard`, { waitUntil: 'networkidle' })
  await page.getByTestId('survey-positive').filter({ hasText: '698' }).waitFor()
  await page.getByTestId('survey-history').waitFor()
  return { page, requests, finish: async () => { await context.close(); assert.deepEqual(errors, []); assert.deepEqual(writes, [], 'Reading survey reports must not write source or clinical records') } }
}
async function changed(page, action) {
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === '/api/platform/operations/dashboard')
  await action()
  const response = await pending
  assert.equal(response.status(), 200)
  const result = await response.json()
  await page.waitForFunction(() => !document.querySelector('[aria-label="รีเฟรชข้อมูล Dashboard"]')?.disabled)
  return result
}
const value = (page, key) => page.locator(`.hsd-stat-${key} .hsd-stat-value strong`)
const heatRow = (page, id, name) => page.getByTestId(id).locator('tbody tr').filter({ has: page.getByRole('rowheader', { name, exact: true }) })

